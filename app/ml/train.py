"""Train the GhostTrace secret-validity model.

The training set is generated by rendering realistic code/config lines that contain either
real-format secrets (random values in each provider's exact format) or the decoys that cause
false positives in keyword scanners (documentation placeholders, env-var references, test
fixtures, low-entropy dummies). Every line runs through the real detection engine, so the
features match what the scanner sees in production. A small amount of label noise is added
(real secrets in test folders, weak-but-real passwords) so the model learns soft boundaries.

Run:  python -m app.ml.train
"""

