ALNUM = string.ascii_letters + string.digits
UPPER_NUM = string.ascii_uppercase + string.digits
B64 = string.ascii_letters + string.digits + "+/"
URLSAFE = string.ascii_letters + string.digits + "-_"
HEX = "0123456789abcdef"


def rnd(alphabet: str, n: int, rng: random.Random) -> str:
    return "".join(rng.choice(alphabet) for _ in range(n))


def b64url(obj: dict) -> str:
    return base64.urlsafe_b64encode(json.dumps(obj).encode()).decode().rstrip("=")


def real_jwt(rng: random.Random) -> str:
    header = b64url({"alg": rng.choice(["HS256", "RS256"]), "typ": "JWT"})
    payload = b64url({"sub": str(rng.randint(1000, 99999999)), "iat": rng.randint(1_600_000_000, 1_760_000_000), "role": rng.choice(["admin", "user", "service"])})
    return f"{header}.{payload}.{rnd(URLSAFE, 43, rng)}"


def human_password(rng: random.Random) -> str:
    words = ["Summer", "Winter", "Dragon", "Monkey", "Falcon", "Tiger", "Galaxy", "Rocket", "Coffee", "Shadow"]
    return f"{rng.choice(words)}{rng.randint(10, 2025)}{rng.choice('!@#$%&*')}"


